"""
run_all.py - ONE command runs the whole project:

    python run_all.py            # full run (all models + tuning)    ~2-6 min on a laptop
    python run_all.py --quick    # fast check that everything works  ~20 s

Steps: load data -> EDA plots -> split -> train/validate/tune regressors -> test
       -> classifiers -> result plots -> advisor demo -> save model + summary.
Everything is written to outputs/ (figures/, results/, models/, run_log.txt).
"""
import argparse
import logging
import sys
import time

import joblib
import pandas as pd

from src import config, plots
from src.data import load_data, split_data
from src.recommend import (BUILDING_SHAPES, building_from_shape, design_optimizer,
                           predict_building, shape_label)
from src.train import build_bundle, train_classifiers, train_regressors


def setup_logging():
    config.OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s | %(message)s", datefmt="%H:%M:%S",
                        handlers=[logging.StreamHandler(sys.stdout),
                                  logging.FileHandler(config.LOG_FILE, mode="w", encoding="utf-8")])
    for noisy in ("matplotlib", "PIL"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
    return logging.getLogger("run_all")


def step(log, n, text):
    log.info("")
    log.info("########## STEP %d: %s ##########", n, text)


def optimizer_summary(bundle):
    """For each of the 12 shapes: a 'typical' design (North, 25% uniform glazing) vs the best design."""
    rows = []
    for i in range(len(BUILDING_SHAPES)):
        b = building_from_shape(i, orientation=2, glazing_area=0.25, glazing_distribution=1)
        cur = predict_building(bundle, b)
        best = design_optimizer(bundle, b).iloc[0]
        rows.append({"shape": shape_label(i), "typical_total_load": cur["total_load"],
                     "typical_class": cur["demand_class"], "best_glazing_area": best.glazing_area,
                     "best_glazing_distribution": best.glazing_distribution,
                     "best_orientation": best.orientation, "best_total_load": best.total_load,
                     "saving_%": best["saving_vs_current_%"]})
    return pd.DataFrame(rows)


def write_summary(df, comparison, test_metrics, clf_comp, clf, opt, minutes):
    """A Markdown summary the team can copy numbers from into the report / PPT."""
    f = lambda d: d.to_markdown(index=False)   # needs the `tabulate` package
    lines = [
        "# Results summary (auto-generated by run_all.py)", "",
        f"- Dataset: UCI Energy Efficiency, {len(df)} buildings, 8 features, 2 targets ({config.DATASET_PAGE})",
        f"- Split: train/validation/test = {1 - config.TEST_SIZE - config.VAL_SIZE:.0%}/"
        f"{config.VAL_SIZE:.0%}/{config.TEST_SIZE:.0%}, random seed {config.RANDOM_STATE}",
        f"- Run time: {minutes:.1f} min", "",
        "## 1. Regression model comparison (validation set + 5-fold CV on train)", "", f(comparison.round(4)), "",
        "## 2. Final models on the hidden TEST set", "", f(test_metrics.round(4)), "",
        "`baseline_RMSE` = always predicting the average load. `interval_margin` = ± width of the 90% "
        "prediction range; `interval_coverage_test` = share of test buildings whose true value fell inside.", "",
        "## 3. Demand classification (Low / Medium / High)", "", f(clf_comp.round(4)), "",
        f"- Thresholds on total load (from training data): {clf['thresholds'][0]:.2f} and {clf['thresholds'][1]:.2f} kWh/m²",
        f"- Best classifier: **{clf['best_model']}** -> test accuracy {clf['test_accuracy']:.4f}, macro-F1 {clf['test_F1_macro']:.4f}",
        f"- Regress-then-classify (predict loads, then apply thresholds) -> test accuracy "
        f"{clf['regress_then_classify_accuracy']:.4f}, macro-F1 {clf['regress_then_classify_F1_macro']:.4f}", "",
        "```", clf["report"], "```", "",
        "## 4. Design optimizer (typical design = North-facing, 25% uniform glazing)", "", f(opt.round(2)), "",
        f"- Average saving available from window/orientation changes alone: {opt['saving_%'].mean():.1f}% "
        f"(max {opt['saving_%'].max():.1f}%)",
    ]
    (config.RESULTS_DIR / "RESULTS_SUMMARY.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description="SmartHVAC Advisor - full ML pipeline")
    parser.add_argument("--quick", action="store_true", help="fewer models, no tuning (fast smoke test)")
    args = parser.parse_args()

    log = setup_logging()
    t0 = time.time()
    for d in (config.FIG_DIR, config.RESULTS_DIR, config.MODEL_DIR):
        d.mkdir(parents=True, exist_ok=True)
    log.info("SmartHVAC Advisor | mode = %s", "QUICK" if args.quick else "FULL")

    step(log, 1, "Load and check data")
    df = load_data()
    df.describe().T.round(3).to_csv(config.RESULTS_DIR / "data_summary_statistics.csv")

    step(log, 2, "Exploratory data analysis (figures 01-04)")
    plots.eda_figures(df)

    step(log, 3, "Split data into train / validation / test")
    train, val, test = split_data(df)

    step(log, 4, "Train, validate, tune and test regression models")
    comparison, test_metrics, art = train_regressors(train, val, test, quick=args.quick)
    comparison.to_csv(config.RESULTS_DIR / "regression_model_comparison.csv", index=False)
    test_metrics.to_csv(config.RESULTS_DIR / "regression_test_metrics.csv", index=False)

    step(log, 5, "Train and test demand classifiers")
    clf_comp, clf, classifier = train_classifiers(train, val, test, art, quick=args.quick)
    clf_comp.to_csv(config.RESULTS_DIR / "classification_model_comparison.csv", index=False)
    (config.RESULTS_DIR / "classification_report.txt").write_text(clf["report"], encoding="utf-8")

    step(log, 6, "Result figures (05-11)")
    train_val = pd.concat([train, val])
    plots.model_comparison_figure(comparison)
    plots.predicted_vs_actual_figure(test, art)
    plots.residuals_figure(test, art)
    plots.feature_importance_figure(art)
    plots.confusion_matrix_figure(clf)
    heat = art["heating_load"]
    plots.learning_curve_figure(heat["model"], train_val[config.FEATURES], train_val["heating_load"], heat["name"])
    plots.partial_dependence_figure(heat["model"], train_val[config.FEATURES], heat["name"])

    step(log, 7, "Save model bundle + run the advisor on all 12 building shapes")
    bundle = build_bundle(art, clf, classifier)
    joblib.dump(bundle, config.MODEL_BUNDLE)
    log.info("  saved %s", config.MODEL_BUNDLE)
    opt = optimizer_summary(bundle)
    opt.to_csv(config.RESULTS_DIR / "design_optimizer_summary.csv", index=False)
    log.info("  average saving from window/orientation changes: %.1f%%", opt["saving_%"].mean())

    minutes = (time.time() - t0) / 60
    write_summary(df, comparison, test_metrics, clf_comp, clf, opt, minutes)
    log.info("")
    log.info("DONE in %.1f min. See outputs/results/RESULTS_SUMMARY.md and outputs/figures/", minutes)
    log.info("Launch the GUI with:  streamlit run app.py")


if __name__ == "__main__":
    main()
